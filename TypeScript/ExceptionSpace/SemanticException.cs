namespace TypeScript.ExceptionSpace;

public enum SemanticErrorType {
    SYMBOL_EXIST,
    SYMBOL_NOT_EXIST,
    LABEL_NOT_EXIST,
    TOO_LARGE_INTEGER,
    NOT_CALLABLE,
    NOT_WRITEABLE,
    NOT_VALUE,
    NOT_TYPE,
    NO_NAME_SPACE,
    NOT_CLASS,
    NOT_PLACE,
    NOT_METHOD,
    NOT_CONCEPT,
    MAY_NOT_RETURN,
    MAY_NOT_INITIALIZED,
    OPERATION_NOT_EXIST,
    NOT_IN_LOOP,
    WRONG_PARAMETER_COUNT,
    WRONG_TYPE,
    WRONG_FIELD_COUNT,
    FIELD_EXIST,
    FIELD_NOT_EXIST,
    METHOD_NOT_EXIST,
    UNKNOWN_TYPE,
    EXTERNAL_TYPE_IMPLEMENTED,
    INVALID_THIS,
    MISSING_FUNCTION_BODY,
    CONCEPT_FUNCTION_NOT_EXIST,
    NOT_IMPLEMENTING_CONCEPT_FUNCTION,
    CONCEPT_NOT_IMPLEMENTED,
}

public class SemanticException(SemanticErrorType type, string[] parameters, SourcePosition position) : Exception($"{position.source}:{position.line}:{position.column}: {formatter[type](parameters)}") {
    static readonly Dictionary<SemanticErrorType, Func<string[], string>> formatter = new() {
        { SemanticErrorType.SYMBOL_EXIST, parameters => $"符号 {parameters[0]} 已存在" },
        { SemanticErrorType.SYMBOL_NOT_EXIST, parameters => $"符号 {parameters[0]} 不存在" },
        { SemanticErrorType.LABEL_NOT_EXIST, parameters => $"标签 {parameters[0]} 不存在" },
        { SemanticErrorType.TOO_LARGE_INTEGER, parameters => $"整数 {parameters[0]} 太大" },
        { SemanticErrorType.NOT_CALLABLE, parameters => $"{parameters[0]} 不是可调用的" },
        { SemanticErrorType.NOT_WRITEABLE, parameters => $"{parameters[0]} 不是可写的" },
        { SemanticErrorType.NOT_VALUE, parameters => $"{parameters[0]} 不是值" },
        { SemanticErrorType.NOT_TYPE, parameters => $"{parameters[0]} 不是类型" },
        { SemanticErrorType.NO_NAME_SPACE, parameters => $"{parameters[0]} 没有名字空间" },
        { SemanticErrorType.NOT_CLASS, parameters => $"{parameters[0]} 不是类" },
        { SemanticErrorType.NOT_PLACE, parameters => "不是位置式" },
        { SemanticErrorType.NOT_METHOD, parameters => $"{parameters[0]} 不是方法" },
        { SemanticErrorType.NOT_CONCEPT, parameters => $"{parameters[0]} 不是概念" },
        { SemanticErrorType.MAY_NOT_RETURN, parameters => $"{parameters[0]} 可能不返回值" },
        { SemanticErrorType.MAY_NOT_INITIALIZED, parameters => $"{parameters[0]} 可能未初始化" },
        { SemanticErrorType.OPERATION_NOT_EXIST, parameters => $"{parameters[0]} 运算不存在" },
        { SemanticErrorType.NOT_IN_LOOP, parameters => "不在循环中" },
        { SemanticErrorType.WRONG_PARAMETER_COUNT, parameters => $"参数数量 {parameters[0]} 不是所需的 {parameters[1]}" },
        { SemanticErrorType.WRONG_TYPE, parameters => $"类型 {parameters[0]} 不是所需的 {parameters[1]}" },
        { SemanticErrorType.WRONG_FIELD_COUNT, parameters => $"字段数量 {parameters[0]} 不是所需的 {parameters[1]}" },
        { SemanticErrorType.FIELD_EXIST, parameters => $"字段 {parameters[0]} 已存在" },
        { SemanticErrorType.FIELD_NOT_EXIST, parameters => $"{parameters[0]} 没有字段 {parameters[1]}" },
        { SemanticErrorType.METHOD_NOT_EXIST, parameters => $"{parameters[0]} 没有方法 {parameters[1]}" },
        { SemanticErrorType.UNKNOWN_TYPE, parameters => $"未知类型" },
        { SemanticErrorType.EXTERNAL_TYPE_IMPLEMENTED, parameters => $"实现了外部类型 {parameters[0]}" },
        { SemanticErrorType.INVALID_THIS, parameters => "无效的 this" },
        { SemanticErrorType.MISSING_FUNCTION_BODY, parameters => "缺少函数体" },
        { SemanticErrorType.CONCEPT_FUNCTION_NOT_EXIST, parameters => $"概念 {parameters[0]} 没有函数 {parameters[1]}" },
        { SemanticErrorType.NOT_IMPLEMENTING_CONCEPT_FUNCTION, parameters => $"该函数未实现概念函数 {parameters[0]}" },
        { SemanticErrorType.CONCEPT_NOT_IMPLEMENTED, parameters => $"未实现概念项 {parameters[0]}" },
    };
}
